export function useTranslations(lang: SupportedLanguage) {
  return function t<K extends keyof typeof ui['en']>(key: K): string {
    const translations = ui[lang] || ui[defaultLang];
    return (translations[key] as string) || (ui[defaultLang][key] as string) || '';
  };
}

export function getLocalizedPath(path: string, lang: SupportedLanguage): string {
  const cleanPath = path.replace(/^\/(en|es|pt|de|fr|ja|zh|ru)(\/|$)/, '/');
  if (lang === defaultLang) {
    return cleanPath === '' ? '/' : cleanPath;
  }
  return `/${lang}${cleanPath === '/' ? '' : cleanPath}`;
}
